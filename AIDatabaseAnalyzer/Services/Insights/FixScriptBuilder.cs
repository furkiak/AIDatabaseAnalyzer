using System.Globalization;
using System.Text;
using AIDatabaseAnalyzer.Models;
using AIDatabaseAnalyzer.Services.Database;

namespace AIDatabaseAnalyzer.Services.Insights;

/// <summary>
/// Turns the mechanical findings into a reviewed SQL script without any AI: indexes for foreign keys (ready to run),
/// redundant indexes and missing primary keys (commented out, they need a human decision).
/// </summary>
public static class FixScriptBuilder
{
    public sealed record Result(string Sql, int Statements, int Suggestions);

    public static Result Build(DatabaseSchema schema, DateTime? now = null)
    {
        var engine = schema.Engine;
        var sb = new StringBuilder();
        int statements = 0, suggestions = 0;

        sb.AppendLine($"-- Fix script for {schema.DatabaseName} ({engine.DisplayName()})");
        sb.AppendLine($"-- Generated by AI Database Analyzer on {(now ?? DateTime.Now).ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture)} from the schema metadata.");
        sb.AppendLine("-- Review every statement and run it on a copy of the database first.");
        if (engine == DbEngine.PostgreSql)
            sb.AppendLine("-- CREATE INDEX CONCURRENTLY cannot run inside a transaction block: execute the statements one by one.");
        sb.AppendLine();

        // 1. foreign keys without an index: safe, ready to run
        var unindexed = schema.IndexesIncluded ? SchemaInsightsService.UnindexedForeignKeys(schema).ToList() : new List<ForeignKeyInfo>();
        sb.AppendLine($"-- 1. Indexes for foreign keys ({unindexed.Count})");
        if (!schema.IndexesIncluded) sb.AppendLine("--    Indexes were not extracted, so missing foreign key indexes could not be determined.");
        else if (unindexed.Count == 0) sb.AppendLine("--    Every foreign key is already covered by an index.");
        else sb.AppendLine("--    Joins and deletes on the parent table scan these tables completely without them.");
        var usedNames = new HashSet<string>(schema.Indexes.Select(i => i.Name), StringComparer.OrdinalIgnoreCase);
        foreach (var fk in unindexed)
        {
            var table = schema.FindTable(fk.FromTable);
            if (table is null) continue;
            string name = IndexName(table.Name, fk.FromColumns, engine, usedNames);
            sb.AppendLine(CreateIndex(engine, table, name, fk.FromColumns));
            statements++;
        }
        sb.AppendLine();

        // 2. redundant indexes: commented out
        var redundant = schema.IndexesIncluded ? SchemaInsightsService.RedundantIndexes(schema).ToList() : new();
        sb.AppendLine($"-- 2. Redundant indexes ({redundant.Count}) — commented out: check the usage statistics before dropping them.");
        if (redundant.Count == 0) sb.AppendLine("--    None found.");
        foreach (var (tableName, index, keep, exact) in redundant)
        {
            var table = schema.FindTable(tableName);
            if (table is null) continue;
            sb.AppendLine($"-- {(exact ? "same columns as" : "left prefix of")} {keep.Name} ({string.Join(", ", keep.Columns)})");
            sb.AppendLine("-- " + DropIndex(engine, table, index.Name));
            suggestions++;
        }
        sb.AppendLine();

        // 3. tables without a primary key: commented out
        var noKey = schema.Tables.Where(t => !t.HasPrimaryKey).ToList();
        sb.AppendLine($"-- 3. Tables without a primary key ({noKey.Count}) — commented out: pick the right key first.");
        if (noKey.Count == 0) sb.AppendLine("--    Every table has a primary key.");
        foreach (var table in noKey)
        {
            string name = SqlCatalog.SqlName(engine, table);
            var candidate = table.Columns.FirstOrDefault(c => c.Name.Equals("id", StringComparison.OrdinalIgnoreCase));
            if (candidate is not null && engine != DbEngine.Sqlite)
            {
                sb.AppendLine($"-- {name}: “{candidate.Name}” looks like the key; make sure it is unique{(candidate.IsNullable ? " and has no NULLs" : "")} first.");
                if (candidate.IsNullable) sb.AppendLine("-- " + SetNotNull(engine, name, candidate));
                sb.AppendLine($"-- ALTER TABLE {name} ADD CONSTRAINT {Q(engine, Shorten("pk_" + table.Name))} PRIMARY KEY ({Q(engine, candidate.Name)});");
            }
            else
            {
                sb.AppendLine($"-- {name}: no obvious key column; add a surrogate key:");
                sb.AppendLine("-- " + AddSurrogateKey(engine, table, name));
            }
            suggestions++;
        }

        return new Result(sb.ToString(), statements, suggestions);
    }

    private static string Q(DbEngine engine, string identifier) => SqlCatalog.QuoteIfNeeded(engine, identifier);

    private static string Columns(DbEngine engine, IEnumerable<string> columns) => string.Join(", ", columns.Select(c => Q(engine, c)));

    private static string CreateIndex(DbEngine engine, TableInfo table, string name, IReadOnlyList<string> columns)
    {
        string target = SqlCatalog.SqlName(engine, table);
        string cols = Columns(engine, columns);
        return engine switch
        {
            DbEngine.SqlServer =>
                $"IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'{name.Replace("'", "''")}' AND object_id = OBJECT_ID(N'{SqlCatalog.QuoteTable(engine, table).Replace("'", "''")}'))\n" +
                $"    CREATE INDEX {Q(engine, name)} ON {target} ({cols}); -- add WITH (ONLINE = ON) on Enterprise / Azure SQL",
            DbEngine.PostgreSql => $"CREATE INDEX CONCURRENTLY IF NOT EXISTS {Q(engine, name)} ON {target} ({cols});",
            DbEngine.Sqlite => $"CREATE INDEX IF NOT EXISTS {Q(engine, name)} ON {target} ({cols});",
            DbEngine.Oracle => $"CREATE INDEX {Q(engine, name)} ON {target} ({cols}); -- add ONLINE on Enterprise Edition",
            _ => $"CREATE INDEX {Q(engine, name)} ON {target} ({cols});"
        };
    }

    private static string DropIndex(DbEngine engine, TableInfo table, string index) => engine switch
    {
        DbEngine.SqlServer or DbEngine.MySql => $"DROP INDEX {Q(engine, index)} ON {SqlCatalog.SqlName(engine, table)};",
        DbEngine.PostgreSql when !string.IsNullOrEmpty(table.Schema) && table.Schema != table.DefaultSchema =>
            $"DROP INDEX CONCURRENTLY IF EXISTS {Q(engine, table.Schema)}.{Q(engine, index)};",
        DbEngine.PostgreSql => $"DROP INDEX CONCURRENTLY IF EXISTS {Q(engine, index)};",
        DbEngine.Sqlite => $"DROP INDEX IF EXISTS {Q(engine, index)};",
        _ => $"DROP INDEX {Q(engine, index)};"
    };

    private static string SetNotNull(DbEngine engine, string table, ColumnInfo column) => engine switch
    {
        DbEngine.SqlServer => $"ALTER TABLE {table} ALTER COLUMN {Q(engine, column.Name)} {column.DataType} NOT NULL;",
        DbEngine.MySql => $"ALTER TABLE {table} MODIFY {Q(engine, column.Name)} {column.DataType} NOT NULL;",
        DbEngine.Oracle => $"ALTER TABLE {table} MODIFY ({Q(engine, column.Name)} NOT NULL);",
        _ => $"ALTER TABLE {table} ALTER COLUMN {Q(engine, column.Name)} SET NOT NULL;"
    };

    private static string AddSurrogateKey(DbEngine engine, TableInfo table, string name) => engine switch
    {
        DbEngine.SqlServer => $"ALTER TABLE {name} ADD id bigint IDENTITY(1,1) NOT NULL CONSTRAINT {Q(engine, "pk_" + table.Name)} PRIMARY KEY;",
        DbEngine.PostgreSql => $"ALTER TABLE {name} ADD COLUMN id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;",
        DbEngine.MySql => $"ALTER TABLE {name} ADD COLUMN id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY FIRST;",
        DbEngine.Oracle => $"ALTER TABLE {name} ADD (id NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT {Q(engine, Shorten("PK_" + table.Name.ToUpperInvariant()))} PRIMARY KEY);",
        _ => $"SQLite cannot add a primary key to {name} in place: create a new table with the key, copy the rows, drop the old one and rename."
    };

    /// <summary>ix_&lt;table&gt;_&lt;columns&gt;, unique within the schema and short enough for every engine.</summary>
    private static string IndexName(string table, IEnumerable<string> columns, DbEngine engine, HashSet<string> used)
    {
        string raw = "ix_" + table + "_" + string.Join("_", columns);
        string clean = new(raw.Select(c => char.IsLetterOrDigit(c) || c == '_' ? c : '_').ToArray());
        if (engine == DbEngine.Oracle) clean = clean.ToUpperInvariant();
        else if (engine == DbEngine.PostgreSql) clean = clean.ToLowerInvariant();
        string name = Shorten(clean);
        string candidate = name;
        for (int i = 2; used.Contains(candidate); i++) candidate = Shorten(name, 4) + "_" + i;
        used.Add(candidate);
        return candidate;
    }

    /// <summary>PostgreSQL truncates names at 63 bytes, MySQL allows 64, Oracle 128 (30 before 12.2): stay at 60.</summary>
    private static string Shorten(string name, int reserve = 0)
    {
        int max = 60 - reserve;
        return name.Length <= max ? name : name[..max];
    }
}
